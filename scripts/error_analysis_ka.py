"""Georgian error analysis tables (docs/error-analysis-georgian-data.md), from committed test runs only.

    uv run python scripts/error_analysis_ka.py > docs/error-analysis-georgian-data.md

Everything here is descriptive: it reads the frozen test predictions/item scores already reported in
docs/results-georgian.md and selects nothing (no checkpoint, decoder or normalizer choice is made from it).
All rates use the declared scoring policy (configs/scoring.yaml), the same as the main results.
"""

from __future__ import annotations

import contextlib
import glob
import importlib.util
import io
import json
import re
from collections import Counter, defaultdict

import jiwer
import numpy as np

from asrbench.dataset import load_manifest
from asrbench.normalize import load_policies

SYSTEMS = [  # (short label, run prefix, group)
    ("Whisper-small", "whisper-small", "baseline"),
    ("Whisper-large-v3", "whisper-large-v3", "baseline"),
    ("Whisper-turbo", "whisper-large-v3-turbo", "baseline"),
    ("XLS-R xsway", "xlsr-georgian-xsway", "baseline"),
    ("MMS kat", "mms-1b-all-kat", "baseline"),
    ("NVIDIA FC*", "nvidia-stt-ka-fastconformer", "baseline"),
    ("GMM-HMM tri3b", "kaldi-gmm-hmm-tri3b", "baseline"),
    ("MMS kat FT", "mms-1b-all-kat-adapter-ft_cv-ka", "ours"),
    ("Whisper-turbo FT", "whisper-large-v3-turbo-ft_cv-ka", "ours"),
]
SETS = [("cv", "CV ka", "data/cv/ka/manifest.jsonl"), ("fleurs", "FLEURS ka", "data/fleurs/ka_ge/manifest.jsonl")]
POLICY = load_policies("configs/scoring.yaml").for_language("ka")
DIGIT = re.compile(r"\d")


def run_dir(prefix: str, ds: str, split: str = "test") -> str | None:
    runs = sorted(glob.glob(f"runs/{prefix}_{ds}-ka_{split}_*"))
    return runs[-1] if runs else None


def items(prefix: str, ds: str) -> dict[str, dict]:
    r = run_dir(prefix, ds)
    if not r:
        return {}
    out = {j["id"]: j for j in map(json.loads, open(f"{r}/item_scores.jsonl", encoding="utf-8"))}
    for p in map(json.loads, open(f"{r}/predictions.jsonl", encoding="utf-8")):
        if p["id"] in out:
            out[p["id"]]["raw_hyp"] = p["hypothesis"]
    return {k: v for k, v in out.items() if v["ref_norm"]}  # silent clips are reported separately in each run


def pct(a: float, b: float) -> str:
    return "—" if not b else f"{100 * a / b:.1f}"


def wsum(rows, key="words"):
    c = Counter()
    for r in (rows.values() if isinstance(rows, dict) else rows):
        c.update(r[key])
    return c


def wer(rows) -> str:
    c = wsum(rows)
    return pct(c["S"] + c["D"] + c["I"], c["N"])


def cer(rows) -> str:
    c = wsum(rows, "chars")
    return pct(c["S"] + c["D"] + c["I"], c["N"])


def table(head: list[str], rows: list[list]) -> list[str]:
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(map(str, r)) + " |" for r in rows]


def loops(hyp: str) -> bool:
    """A decoding loop: some 1-4-gram repeated 4+ times in a row."""
    t = hyp.split()
    for n in range(1, 5):
        for i in range(0, len(t) - 4 * n + 1):
            g = t[i:i + n]
            if all(t[i + k * n:i + (k + 1) * n] == g for k in range(1, 4)):
                return True
    return False


def main() -> None:
    data = {(p, ds): items(p, ds) for _, p, _ in SYSTEMS for ds, _, _ in SETS}
    meta = {ds: {it.id: it for it in load_manifest(m).items} for ds, _, m in SETS}
    train = [it for it in meta["cv"].values() if it.split == "train"]
    vocab = {w for it in train for w in POLICY.normalize(it.reference).split()}
    L = ["# Georgian error analysis: data tables", "",
         "Generated by `scripts/error_analysis_ka.py` from the committed frozen-test runs; do not edit by hand. "
         "Descriptive only (nothing is selected on test). Normalized text under `configs/scoring.yaml`. "
         "Rates are % of reference words (or characters); silent clips excluded. "
         "\\* NVIDIA has seen many CV clips in training (see §7).", ""]

    # 1. Error composition
    L += ["## 1. Error composition (test)", "",
          "S/D/I = substitutions, deletions, insertions as % of reference words; Hyp/Ref = hypothesis words per "
          "reference word.", ""]
    rows = []
    for ds, dsname, _ in SETS:
        for label, p, g in SYSTEMS:
            r = list(data[(p, ds)].values())
            if not r:
                continue
            c = wsum(r)
            rows.append([dsname, g, label, wer(r), pct(c["S"], c["N"]), pct(c["D"], c["N"]), pct(c["I"], c["N"]),
                         f"{c['M'] / c['N']:.2f}", cer(r)])
    L += table(["Set", "Group", "System", "WER", "S", "D", "I", "Hyp/Ref", "CER"], rows) + [""]

    # 2. Length / truncation
    def dur_stats(its):
        d = np.array([it.duration for it in its if it.duration])
        w = np.array([len(POLICY.normalize(it.reference).split()) for it in its])
        return [len(its), f"{np.median(d):.1f}", f"{np.percentile(d, 95):.1f}", f"{d.max():.1f}", f"{np.median(w):.0f}",
                f"{np.percentile(w, 95):.0f}"]
    L += ["## 2. Utterance length and deletions", "",
          "Clip length of the fine-tuning data (CV train) against the test sets:", ""]
    L += table(["Data", "Clips", "Median s", "95th pct s", "Max s", "Median words", "95th pct words"],
               [["CV ka train", *dur_stats(train)]] +
               [[f"{n} test", *dur_stats([it for it in meta[ds].values() if it.split == "test"])] for ds, n, _ in SETS]) + [""]
    edges = [(1, 8), (9, 14), (15, 20), (21, 30), (31, 999)]
    L += ["WER (and deletion rate D) by reference length in words, test:", ""]
    rows = []
    for ds, dsname, _ in SETS:
        for label, p, g in SYSTEMS:
            r = data[(p, ds)]
            if not r or label in ("Whisper-small", "Whisper-turbo"):
                continue
            cells = []
            for lo, hi in edges:
                b = [x for x in r.values() if lo <= x["words"]["N"] <= hi]
                c = wsum(b)
                cells.append(f"{wer(b)} (D {pct(c['D'], c['N'])})" if b else "—")
            rows.append([dsname, label, *cells])
    counts = {ds: [sum(1 for x in data[("mms-1b-all-kat", ds)].values() if lo <= x["words"]["N"] <= hi) for lo, hi in edges]
              for ds, _, _ in SETS}
    L += table(["Set", "System"] + [f"{lo}–{hi if hi < 999 else '∞'} words" for lo, hi in edges], rows)
    L += ["", "Clips per bucket: " + "; ".join(f"{n}: " + ", ".join(map(str, counts[ds])) for ds, n, _ in SETS), ""]

    # 3. Digits
    L += ["## 3. Digits in references (FLEURS ka test)", "",
          "The policy does not verbalize numbers, so a reference \"2015\" only matches a hypothesis \"2015\". "
          "CV ka train transcripts contain almost no digits (count below).", ""]
    n_train_digit = sum(1 for it in train if DIGIT.search(it.reference))
    rows = []
    fl = data[("mms-1b-all-kat", "fleurs")]
    dig_ids = {k for k, v in fl.items() if DIGIT.search(v["ref_norm"])}
    for label, p, g in SYSTEMS:
        r = data[(p, "fleurs")]
        if not r:
            continue
        a = [v for k, v in r.items() if k in dig_ids]
        b = [v for k, v in r.items() if k not in dig_ids]
        hyp_dig = sum(1 for v in a if DIGIT.search(v["hyp_norm"]))
        rows.append([g, label, wer(a), cer(a), wer(b), cer(b), pct(hyp_dig, len(a))])
    L += [f"CV ka train clips with a digit: {n_train_digit} of {len(train)}. FLEURS ka test clips with a digit in the "
          f"reference: {len(dig_ids)} of {len(fl)}.", ""]
    L += table(["Group", "System", "WER (digit refs)", "CER (digit refs)", "WER (other refs)", "CER (other refs)",
                "% of digit refs where hyp has a digit"], rows) + [""]

    # 4. Loops
    L += ["## 4. Repetition loops", "",
          "Loop = some 1–4-gram repeated 4+ times in a row in the normalized hypothesis. Share of insertions = "
          "insertions inside loop clips / all insertions.", ""]
    rows = []
    for ds, dsname, _ in SETS:
        for label, p, g in SYSTEMS:
            r = data[(p, ds)]
            if not r:
                continue
            lp = [v for v in r.values() if loops(v["hyp_norm"])]
            ins_all = wsum(r.values())["I"]
            ins_lp = wsum(lp)["I"]
            no_loop = [v for v in r.values() if not loops(v["hyp_norm"])]
            rows.append([dsname, label, f"{len(lp)} ({pct(len(lp), len(r))}%)", pct(ins_lp, ins_all), wer(r), wer(no_loop)])
    L += table(["Set", "System", "Loop clips", "Share of insertions", "WER", "WER without loop clips"], rows) + [""]

    # 5. OOV
    L += ["## 5. Out-of-vocabulary words (w.r.t. CV ka train transcripts)", "",
          f"Vocabulary = the {len(vocab)} word types of the normalized CV ka train transcripts (the GMM-HMM's closed "
          "lexicon is this set minus 5 clips with non-Georgian characters). OOV recall = share of OOV reference "
          "tokens that the alignment marks as correct. The GMM-HMM cannot output an OOV word, so its OOV recall is 0 "
          "by construction.", ""]
    rows = []
    for ds, dsname, _ in SETS:
        ref = data[("mms-1b-all-kat", ds)]
        n_tok = sum(len(v["ref_norm"].split()) for v in ref.values())
        n_oov = sum(1 for v in ref.values() for w in v["ref_norm"].split() if w not in vocab)
        L += [f"{dsname} test: {n_oov} of {n_tok} reference tokens are OOV ({pct(n_oov, n_tok)}%).", ""]
        for label, p, g in SYSTEMS:
            r = data[(p, ds)]
            if not r or label in ("Whisper-small", "Whisper-turbo"):
                continue
            hit = tot = 0
            for v in r.values():
                rt = v["ref_norm"].split()
                oov_pos = {i for i, w in enumerate(rt) if w not in vocab}
                if not oov_pos:
                    continue
                tot += len(oov_pos)
                if not v["hyp_norm"]:
                    continue
                al = jiwer.process_words(v["ref_norm"], v["hyp_norm"]).alignments[0]
                for ch in al:
                    if ch.type == "equal":
                        hit += len(oov_pos & set(range(ch.ref_start_idx, ch.ref_end_idx)))
            with_oov = [v for v in r.values() if any(w not in vocab for w in v["ref_norm"].split())]
            without = [v for v in r.values() if not any(w not in vocab for w in v["ref_norm"].split())]
            rows.append([dsname, g, label, pct(hit, tot), wer(with_oov), wer(without)])
    L += table(["Set", "Group", "System", "OOV recall", "WER, clips with OOV", "WER, clips without OOV"], rows) + [""]

    # 6. Speakers / demographics (CV)
    L += ["## 6. Speakers (CV ka test)", "",
          "CV ka train has 139 speakers, test 1058 (all unseen). Per-speaker WER over speakers with >= 50 reference "
          "words; gender/age as self-reported in CV metadata (blank = not given).", ""]
    rows = []
    for label, p, g in SYSTEMS:
        r = data[(p, "cv")]
        if not r or label in ("Whisper-small", "Whisper-turbo"):
            continue
        per = defaultdict(Counter)
        for k, v in r.items():
            per[meta["cv"][k].speaker].update(v["words"])
        s = np.array([(c["S"] + c["D"] + c["I"]) / c["N"] for c in per.values() if c["N"] >= 50]) * 100
        rows.append([g, label, len(s), f"{np.percentile(s, 10):.1f}", f"{np.median(s):.1f}", f"{np.percentile(s, 90):.1f}",
                     f"{s.max():.1f}"])
    L += table(["Group", "System", "Speakers", "10th pct WER", "Median", "90th pct", "Max"], rows) + [""]
    for field in ("gender", "age"):
        groups = Counter(meta["cv"][k].extra.get(field) or "(blank)" for k in data[("mms-1b-all-kat", "cv")])
        keys = [k for k, n in groups.most_common() if n >= 200]
        rows = []
        for label, p, g in SYSTEMS:
            r = data[(p, "cv")]
            if not r or label in ("Whisper-small", "Whisper-turbo"):
                continue
            rows.append([g, label] + [wer([v for k2, v in r.items() if (meta["cv"][k2].extra.get(field) or "(blank)") == k])
                                      for k in keys])
        L += [f"WER by {field} (groups with >= 200 test clips; clips per group: "
              + ", ".join(f"{k} {groups[k]}" for k in keys) + "):", ""]
        L += table(["Group", "System"] + keys, rows) + [""]

    # 7. Contamination
    spec = importlib.util.spec_from_file_location("cvc", "scripts/cv_contamination.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        mod.main(["nvidia-stt-ka-fastconformer", "mms-1b-all-kat", "kaldi-gmm-hmm-tri3b", "whisper-large-v3-turbo-ft_cv-ka"])
    L += ["## 7. Training-data contamination check (CV ka dev + test by clip ID)", "",
          "Output of `scripts/cv_contamination.py` (corpus WER per clip-ID range; newer clips have larger IDs). "
          "NVIDIA's model card lists CV 17.0 train/dev/other as training data.", "", buf.getvalue().rstrip(), ""]

    # 8. Substitutions
    L += ["## 8. Most frequent word substitutions (CV ka test)", ""]
    for label, p in (("Whisper-turbo FT (ours)", "whisper-large-v3-turbo-ft_cv-ka"), ("MMS kat (baseline)", "mms-1b-all-kat"),
                     ("GMM-HMM tri3b (baseline)", "kaldi-gmm-hmm-tri3b")):
        r = data[(p, "cv")]
        c = Counter()
        char_edits = []
        for v in r.values():
            if not v["hyp_norm"]:
                continue
            o = jiwer.process_words(v["ref_norm"], v["hyp_norm"])
            for ch in o.alignments[0]:
                if ch.type == "substitute":
                    pairs = list(zip(o.references[0][ch.ref_start_idx:ch.ref_end_idx], o.hypotheses[0][ch.hyp_start_idx:ch.hyp_end_idx]))
                    c.update(pairs)
                    char_edits += [jiwer.process_characters(a, b) for a, b in pairs]
        n = sum(c.values())
        one = sum(1 for e in char_edits if e.substitutions + e.deletions + e.insertions == 1)
        L += [f"**{label}**: {n} substituted words; {pct(one, n)}% differ from the reference word by a single character "
              "edit.", ""]
        L += table(["Reference", "Hypothesis", "Count"], [[a, b, k] for (a, b), k in c.most_common(10)]) + [""]
    print("\n".join(L))


if __name__ == "__main__":
    main()
